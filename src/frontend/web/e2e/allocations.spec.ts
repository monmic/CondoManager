import { test, expect } from '@playwright/test'

test('riparti reali: regole, gruppo, consumi, preview e conferma con snapshot', async ({ page }) => {
  test.skip(!process.env.CONDOMANAGER_E2E, 'Avviare scripts/Verify-Postgres.ps1 -Browser su PostgreSQL isolato.')
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill(process.env.CONDOMANAGER_E2E_EMAIL!)
  await page.getByLabel('Password', { exact: true }).fill(process.env.CONDOMANAGER_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Accedi', exact: true }).click()
  await page.getByRole('button', { name: 'Condomini', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo condominio', exact: true }).click()
  await page.getByLabel('Codice interno').fill('C-ALLOC')
  await page.getByLabel('Denominazione').fill('Condominio riparti sintetico')
  await page.getByLabel('Indirizzo').fill('Indirizzo sintetico')
  await page.getByLabel('CAP').fill('00000')
  await page.getByLabel('Comune').fill('Comune sintetico')
  await page.getByLabel('Provincia').fill('XX')
  await page.getByLabel('Stato').fill('Test')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Condominio riparti sintetico', exact: true })).toBeVisible()
  for (const code of ['A', 'B', 'C']) {
    await page.getByRole('button', { name: 'Nuova unita', exact: true }).click()
    await page.getByLabel('Codice unita').fill(code)
    await page.getByRole('button', { name: 'Salva', exact: true }).click()
    await expect(page.getByRole('cell', { name: code, exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Esercizi contabili', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo esercizio' }).click()
  await page.getByLabel('Codice esercizio').fill('E-ALLOC')
  await page.getByLabel('Denominazione').fill('Esercizio riparti sintetico')
  await page.getByLabel('Data inizio').fill('2026-01-01')
  await page.getByLabel('Data fine').fill('2026-12-31')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await page.getByRole('button', { name: 'Apri esercizio', exact: true }).click()
  await page.getByRole('button', { name: 'Tabelle millesimali', exact: true }).click()
  await page.getByRole('button', { name: 'Nuova tabella', exact: true }).click()
  await page.getByLabel('Codice tabella').fill('T-ALLOC')
  await page.getByLabel('Denominazione').fill('Tabella riparti sintetica')
  await page.getByLabel('Decorrenza').fill('2026-01-01')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  for (const [code, value] of [['A', '500'], ['B', '300'], ['C', '200']]) {
    const input = page.getByLabel('Quota ' + code, { exact: true })
    await input.fill(value)
    await input.locator('..').getByRole('button', { name: 'Salva quota' }).click()
    await expect(page.getByRole('cell', { name: value + '.000000', exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Attiva', exact: true }).click()
  await page.getByRole('button', { name: 'Contabilità', exact: true }).click()
  await page.getByRole('button', { name: 'Fornitori', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo fornitore' }).click()
  await page.getByLabel('Denominazione fornitore').fill('Fornitore riparti sintetico')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Fornitore riparti sintetico', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Documenti di spesa', exact: true }).click()
  await page.getByRole('button', { name: 'Nuova spesa' }).click()
  await page.getByLabel(/^Fornitore/).selectOption({ label: 'Fornitore riparti sintetico' })
  await page.getByLabel('Categoria di spesa').selectOption({ label: '550 · Manutenzioni ordinarie' })
  await page.getByLabel('Numero documento').fill('SYN-ALLOC-1000')
  await page.getByLabel('Data documento').fill('2026-08-01')
  await page.getByLabel('Descrizione spesa').fill('Spesa sintetica da ripartire')
  await page.getByLabel('Imponibile EUR').fill('1000')
  await page.getByLabel('IVA EUR').fill('0')
  await page.getByLabel('Totale EUR').fill('1000')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await page.getByRole('button', { name: 'Registra', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Registrato', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Ripartizioni', exact: true }).click()
  await page.getByLabel('Esercizio ripartizioni').selectOption({ label: 'Esercizio riparti sintetico · Open' })
  await page.getByRole('button', { name: 'Gruppi', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo gruppo' }).click()
  await page.getByLabel('Nome gruppo').fill('Gruppo sintetico A-B')
  await page.getByLabel('Unita gruppo A', { exact: true }).check()
  await page.getByLabel('Unita gruppo B', { exact: true }).check()
  await page.getByRole('button', { name: 'Salva gruppo', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Gruppo sintetico A-B', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Regole', exact: true }).click()
  await page.getByRole('button', { name: 'Nuova regola', exact: true }).click()
  await page.getByLabel('Nome regola').fill('Parti uguali sintetiche')
  await page.getByRole('button', { name: 'Salva regola', exact: true }).click()
  await page.getByRole('button', { name: 'Attiva regola', exact: true }).click()
  await expect(page.getByText('Attiva', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Nuova regola', exact: true }).click()
  await page.getByLabel('Nome regola').fill('Mista sintetica 30-70')
  await page.getByLabel('Tipo regola').selectOption('Mixed')
  await page.getByLabel('Peso percentuale 1', { exact: true }).fill('30')
  await page.getByLabel('Peso percentuale 2', { exact: true }).fill('70')
  await page.getByLabel('Tabella millesimale 1').selectOption({ label: 'T-ALLOC · Tabella riparti sintetica · Active' })
  await page.getByLabel(/^Tipo consumo 2/).fill('COLDWATER')
  await page.getByLabel('Unita di misura 2', { exact: true }).fill('M3')
  await page.getByRole('button', { name: 'Salva regola', exact: true }).click()
  await page.getByRole('button', { name: 'Attiva regola', exact: true }).click()
  await expect(page.getByText('Attiva', { exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'Consumi', exact: true }).click()
  let count = 0
  for (const [code, final] of [['A', '110'], ['B', '120'], ['C', '140']]) for (const boundary of ['Initial', 'Final']) {
    await page.getByRole('button', { name: 'Nuova lettura', exact: true }).click()
    await page.getByLabel('Unita lettura').selectOption({ label: code })
    await page.getByLabel('Codice contatore').fill('M-' + code)
    await page.getByLabel('Estremo lettura').selectOption(boundary)
    await page.getByLabel('Data lettura').fill(boundary === 'Initial' ? '2026-01-01' : '2026-12-31')
    await page.getByLabel('Valore lettura').fill(boundary === 'Initial' ? '100' : final)
    await page.getByRole('button', { name: 'Salva', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Rettifica lettura', exact: true })).toHaveCount(++count)
  }
  await expect(page.getByText('Non calcolabile', { exact: false })).toHaveCount(0)
  await page.getByRole('button', { name: 'Simulazione', exact: true }).click()
  await page.getByRole('button', { name: 'Aggiungi quota di spesa', exact: true }).click()
  await page.getByLabel('Documento quota 1').selectOption({ label: 'SYN-ALLOC-1000 · Da ripartire 1.000,00 €' })
  await page.getByLabel('Importo quota 1').fill('100')
  await page.getByLabel('Regola quota 1').selectOption({ label: 'Parti uguali sintetiche · v1' })
  await page.getByRole('button', { name: 'Simula ripartizione', exact: true }).click()
  await expect(page.getByRole('cell', { name: '33,34 €', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: '33,33 €', exact: true })).toHaveCount(2)
  await page.getByLabel('Importo quota 1').fill('1000')
  await page.getByLabel('Regola quota 1').selectOption({ label: 'Mista sintetica 30-70 · v1' })
  await page.getByRole('button', { name: 'Simula ripartizione', exact: true }).click()
  for (const value of ['250,00 €', '290,00 €', '460,00 €']) await expect(page.getByRole('cell', { name: value, exact: true })).toBeVisible()
  await expect(page.getByText('Differenza: 0,00 €', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Conferma ripartizione', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Riparto confermato · versione 1', exact: true })).toBeVisible()
  await expect(page.getByText('Mista sintetica 30-70 v1', { exact: false })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('allocations-desktop.png'), fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'Ripartizioni', exact: true }).click()
  const condo = page.getByRole('combobox', { name: 'Condominio', exact: true })
  await condo.selectOption(await condo.locator('option').filter({ hasText: 'C-ALLOC' }).getAttribute('value') ?? '')
  await page.getByRole('button', { name: 'Storico ripartizioni', exact: true }).click()
  await page.getByRole('button', { name: 'Dettaglio riparto', exact: true }).click()
  await expect(page.getByRole('cell', { name: '460,00 €', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.body.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: test.info().outputPath('allocations-mobile.png'), fullPage: true })
})
