import { test, expect } from '@playwright/test'

test('rate e incassi reali: emissione, pagamento parziale, riconciliazione e saldi', async ({ page }) => {
  test.skip(!process.env.CONDOMANAGER_E2E, 'Usare Verify-Postgres.ps1 -Browser con PostgreSQL isolato.')
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill(process.env.CONDOMANAGER_E2E_EMAIL!)
  await page.getByLabel('Password', { exact: true }).fill(process.env.CONDOMANAGER_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Accedi', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Rate e incassi', exact: true })).toBeVisible()
  const fixture = await page.evaluate(async () => {
    const { token } = await (await fetch('/api/auth/csrf')).json() as { token: string }
    async function post<T>(path: string, body: unknown): Promise<T> {
      const r = await fetch('/api' + path, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-TOKEN': token }, body: JSON.stringify(body) })
      if (!r.ok) throw new Error(await r.text())
      return r.json() as Promise<T>
    }
    const condo = await post<{ id: string }>('/condominiums', { code: 'C-FINANCE', name: 'Condominio finanziario sintetico', address: 'Sintetico', postalCode: '00000', city: 'Test', province: 'XX', country: 'Test' })
    for (const code of ['A', 'B', 'C']) {
      const u = await post<{ id: string }>('/condominiums/' + condo.id + '/units', { code, kind: 'Apartment' })
      const p = await post<{ id: string }>('/people', { code: 'FIN-' + code, kind: 'NaturalPerson', firstName: 'Synthetic', lastNameOrCompany: 'Resident ' + code, taxCode: 'SYNTHETIC-FIN-' + code })
      await post('/condominiums/' + condo.id + '/units/' + u.id + '/associations', { personId: p.id, role: 'Owner', validFrom: '2026-01-01', fraction: '1' })
    }
    const p = await post<{ id: string }>('/condominiums/' + condo.id + '/accounting-periods', { code: 'E-FIN', name: 'Esercizio finanziario sintetico', startsOn: '2026-01-01', endsOn: '2026-12-31' })
    await post('/condominiums/' + condo.id + '/accounting-periods/' + p.id + '/open', {})
    const rule = await post<{ id: string }>('/allocations/condominiums/' + condo.id + '/rules', { name: 'Regola finanziaria sintetica', type: 'EqualShares', components: [{ criterion: 'EqualShares', percentage: '100' }] })
    await post('/allocations/condominiums/' + condo.id + '/rules/' + rule.id + '/activate', {})
    const accounts = await (await fetch('/api/accounting/condominiums/' + condo.id + '/accounts')).json() as { id: string; type: string }[]
    const budget = await post<{ id: string }>('/budgets/condominiums/' + condo.id, { accountingPeriodId: p.id, description: 'Preventivo finanziario sintetico', lines: [{ accountId: accounts.find(a => a.type === 'Expense')!.id, description: 'Synthetic preventive expense', amount: '6000', ruleId: rule.id }] })
    await post('/budgets/condominiums/' + condo.id + '/' + budget.id + '/propose', {})
    const preview = await post<{ hash: string }>('/budgets/condominiums/' + condo.id + '/' + budget.id + '/preview', {})
    await post('/budgets/condominiums/' + condo.id + '/' + budget.id + '/approve', { previewHash: preview.hash })
    const bank = await post<{ id: string }>('/accounting/condominiums/' + condo.id + '/financial-accounts', { code: 'FIN-BANK', name: 'Banca finanziaria sintetica', type: 'BankAccount', openingBalance: '0', accountingPeriodId: p.id, date: '2026-01-01', requestId: crypto.randomUUID() })
    const movement = await post<{ id: string }>('/accounting/condominiums/' + condo.id + '/receipts', { requestId: crypto.randomUUID(), accountingPeriodId: p.id, financialAccountId: bank.id, date: '2026-08-01', amount: '250', description: 'Movimento bancario sintetico da riconciliare' })
    return { condo: condo.id, movement: movement.id }
  })
  await page.reload()
  await page.getByRole('button', { name: 'Rate e incassi', exact: true }).click()
  await page.getByRole('combobox', { name: 'Condominio', exact: true }).selectOption(fixture.condo)
  await page.getByRole('button', { name: 'Nuovo piano rateale', exact: true }).click()
  await page.getByRole('combobox', { name: 'Preventivo approvato', exact: true }).selectOption({ label: 'Preventivo finanziario sintetico · v1' })
  await page.getByLabel('Data designazione debitori').fill('2026-01-01')
  await page.getByLabel('Scadenza 1', { exact: true }).fill('2026-02-01')
  for (let i = 2; i <= 4; i++) { await page.getByRole('button', { name: 'Aggiungi scadenza', exact: true }).click(); await page.getByLabel('Scadenza ' + i, { exact: true }).fill(`2026-${String(i * 2).padStart(2, '0')}-01`) }
  for (const code of ['A', 'B', 'C']) await page.getByRole('checkbox', { name: `Designa ${code} Synthetic Resident ${code}`, exact: true }).check()
  await page.getByRole('button', { name: 'Simula piano rateale', exact: true }).click()
  await expect(page.getByRole('cell', { name: '500,00 €', exact: true })).toHaveCount(12)
  await page.getByRole('button', { name: 'Salva piano in bozza', exact: true }).click()
  await page.getByLabel('Data emissione piano').fill('2026-01-01')
  await page.getByRole('button', { name: 'Approva ed emetti crediti', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Piano v1 · Emesso', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Incassi', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo incasso', exact: true }).click()
  await page.getByLabel('Esercizio incasso').selectOption({ label: 'Esercizio finanziario sintetico' })
  await page.getByLabel('Conto finanziario incasso').selectOption({ label: 'Banca finanziaria sintetica' })
  await page.getByLabel('Data incasso').fill('2026-08-01')
  await page.getByLabel('Importo incasso').fill('200')
  await page.getByLabel('Debitore identificato').selectOption({ label: 'Synthetic Resident A' })
  await page.getByLabel('Soggetto pagante').selectOption({ label: 'Synthetic Resident B' })
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await page.getByLabel('Attribuzione A 2026-02-01', { exact: true }).fill('200')
  await page.getByRole('button', { name: 'Conferma attribuzione', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Attribuita', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Rate e crediti', exact: true }).click()
  const rate = page.getByRole('row').filter({ has: page.getByRole('cell', { name: 'A', exact: true }) }).filter({ has: page.getByRole('cell', { name: '2026-02-01', exact: true }) })
  await expect(rate.getByRole('cell', { name: 'Parzialmente pagata', exact: true })).toBeVisible()
  await expect(rate.getByRole('cell', { name: '300,00 €', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Riconciliazione', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo incasso', exact: true }).click()
  await page.getByLabel('Esercizio incasso').selectOption({ label: 'Esercizio finanziario sintetico' })
  await page.getByLabel('Conto finanziario incasso').selectOption({ label: 'Banca finanziaria sintetica' })
  await page.getByLabel('Data incasso').fill('2026-08-01')
  await page.getByLabel('Importo incasso').fill('250')
  await page.getByRole('checkbox', { name: /Da riconciliare con movimento esistente/ }).check()
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await page.getByLabel('Movimento bancario').selectOption(fixture.movement)
  await page.getByRole('button', { name: 'Associa movimento', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Associato', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Conferma riconciliazione', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Riconciliato', exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'Saldi', exact: true }).click()
  await expect(page.getByText('Emesso 6.000,00 € · attribuito 200,00 € · residuo 5.800,00 €', { exact: true })).toBeVisible()
  await expect(page.getByText('Incassi riconciliati non attribuiti 250,00 € · da riconciliare 0,00 €', { exact: true })).toBeVisible()
  const bankBalance = await page.evaluate(async condo => { const rows = await (await fetch('/api/accounting/condominiums/' + condo + '/financial-accounts')).json() as { balance: string }[]; return rows[0].balance }, fixture.condo)
  expect(bankBalance).toBe('450.00')
  await page.screenshot({ path: '../../../.artifacts/finance-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../../../.artifacts/finance-mobile.png', fullPage: true })
})
