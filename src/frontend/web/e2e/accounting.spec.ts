import { test, expect } from '@playwright/test'

test('contabilita reale: fattura, pagamenti parziali, incasso, saldi e storni', async ({ page }) => {
  test.skip(!process.env.CONDOMANAGER_E2E, 'Avviare scripts/Verify-Postgres.ps1 -Browser su database isolato.')
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill(process.env.CONDOMANAGER_E2E_EMAIL!)
  await page.getByLabel('Password', { exact: true }).fill(process.env.CONDOMANAGER_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Accedi', exact: true }).click()
  await page.getByRole('button', { name: 'Condomini', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo condominio' }).click()
  await page.getByLabel('Codice interno').fill('C-LEDGER')
  await page.getByLabel('Denominazione').fill('Condominio contabile sintetico')
  await page.getByLabel('Indirizzo').fill('Indirizzo sintetico')
  await page.getByLabel('CAP').fill('00000')
  await page.getByLabel('Comune').fill('Comune sintetico')
  await page.getByLabel('Provincia').fill('XX')
  await page.getByLabel('Stato').fill('Test')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Condominio contabile sintetico', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Esercizi contabili', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo esercizio' }).click()
  await page.getByLabel('Codice esercizio').fill('E-LEDGER')
  await page.getByLabel('Denominazione').fill('Esercizio contabile sintetico')
  await page.getByLabel('Data inizio').fill('2026-01-01')
  await page.getByLabel('Data fine').fill('2026-12-31')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await page.getByRole('button', { name: 'Apri esercizio', exact: true }).click()
  await page.getByRole('button', { name: 'Contabilità', exact: true }).click()
  await page.getByRole('button', { name: 'Piano dei conti', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Debiti verso fornitori', exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Fornitori', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo fornitore' }).click()
  await page.getByLabel('Denominazione fornitore').fill('Fornitore contabile sintetico')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Fornitore contabile sintetico', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Conti finanziari', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo conto finanziario', exact: true }).click()
  await page.getByLabel('Codice conto contabile').fill('BANK-LEDGER')
  await page.getByLabel('Nome conto finanziario').fill('Banca sintetica')
  await page.getByLabel('Data operazione').fill('2026-01-01')
  await page.getByLabel('Saldo iniziale EUR').fill('500')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Banca sintetica', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Documenti di spesa', exact: true }).click()
  await page.getByRole('button', { name: 'Nuova spesa' }).click()
  await page.getByLabel(/^Fornitore/).selectOption({ label: 'Fornitore contabile sintetico' })
  await page.getByLabel('Categoria di spesa').selectOption({ label: '550 · Manutenzioni ordinarie' })
  await page.getByLabel('Numero documento').fill('SYN-122')
  await page.getByLabel('Data documento').fill('2026-08-01')
  await page.getByLabel('Descrizione spesa').fill('Manutenzione sintetica')
  await page.getByLabel('Imponibile EUR').fill('100')
  await page.getByLabel('IVA EUR').fill('22')
  await page.getByLabel('Totale EUR').fill('122')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Bozza', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Registra', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Registrato', exact: true })).toBeVisible()
  for (const [value, status] of [['22.01', 'Parzialmente pagato'], ['99.99', 'Pagato']]) {
    await page.getByRole('button', { name: 'Paga', exact: true }).click()
    await page.getByLabel('Data operazione').fill('2026-08-02')
    await page.getByLabel(/^Conto finanziario/).selectOption({ label: 'Banca sintetica' })
    await page.getByLabel('Importo pagamento EUR').fill(value)
    await page.getByRole('button', { name: 'Salva', exact: true }).click()
    await expect(page.getByRole('cell', { name: status, exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'SYN-122', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pagamenti · Residuo 0,00 €' })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Contabilizzato', exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'Conti finanziari', exact: true }).click()
  await expect(page.getByRole('cell', { name: '378,00 €', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Registra incasso generico', exact: true }).click()
  await page.getByLabel('Data operazione').fill('2026-08-03')
  await page.getByLabel(/^Conto finanziario/).selectOption({ label: 'Banca sintetica' })
  await page.getByLabel('Importo incasso EUR').fill('200')
  await page.getByLabel('Causale incasso').fill('Incasso sintetico da attribuire')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('cell', { name: '578,00 €', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Movimenti', exact: true }).first().click()
  await page.getByRole('button', { name: 'Incasso sintetico da attribuire', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Scrittura: Incasso sintetico da attribuire' })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Incassi da attribuire', exact: true })).toBeVisible()
  const receiptRow = page.getByRole('row').filter({ has: page.getByRole('button', { name: 'Incasso sintetico da attribuire', exact: true }) })
  await receiptRow.getByRole('button', { name: 'Storna', exact: true }).click()
  await page.getByLabel('Data operazione').fill('2026-08-04')
  await page.getByLabel('Motivo dello storno').fill('Rettifica sintetica incasso')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Rettifica sintetica incasso', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Riepilogo', exact: true }).click()
  await expect(page.locator('.ledger-metrics').getByText('378,00 €', { exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('accounting-desktop.png'), fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'Contabilità', exact: true }).click()
  await page.getByRole('combobox', { name: 'Condominio', exact: true }).selectOption(await page.getByRole('combobox', { name: 'Condominio', exact: true }).locator('option').filter({ hasText: 'C-LEDGER' }).getAttribute('value') ?? '')
  await expect(page.locator('.ledger-metrics').getByText('378,00 €', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.body.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: test.info().outputPath('accounting-mobile.png'), fullPage: true })
})
