import { test, expect } from '@playwright/test'
test('assemblea reale: agenda, snapshot, convocazioni, delega verificata e presenze per sessione', async ({ page }) => {
 test.skip(!process.env.CONDOMANAGER_E2E, 'Usare Verify-Postgres.ps1 -Browser su PostgreSQL isolato.')
 page.on('dialog', d => d.accept('Riferimento sintetico'))
 await page.goto('/')
 await page.getByLabel('Email', { exact: true }).fill(process.env.CONDOMANAGER_E2E_EMAIL!)
 await page.getByLabel('Password', { exact: true }).fill(process.env.CONDOMANAGER_E2E_PASSWORD!)
 await page.getByRole('button', { name: 'Accedi', exact: true }).click()
 await expect(page.getByRole('button', { name: 'Assemblee', exact: true })).toBeVisible()
 const seed = await page.evaluate(async () => {
  const { token } = await (await fetch('/api/auth/csrf')).json() as { token: string }
  async function post<T>(path: string, body: unknown, method = 'POST') { const r = await fetch('/api' + path, { method, headers: { 'Content-Type': 'application/json', 'X-CSRF-TOKEN': token }, body: JSON.stringify(body) }); if (!r.ok) throw new Error(await r.text()); return r.json() as Promise<T> }
  const c = await post<{ id: string }>('/condominiums', { code: 'C-MEETING', name: 'Condominio assemblea sintetico', address: 'Sintetico', postalCode: '00000', city: 'Test', province: 'XX', country: 'Test' })
  const units: string[] = [], people: string[] = []
  for (const code of ['A', 'B']) {
   const u = await post<{ id: string }>('/condominiums/' + c.id + '/units', { code, kind: 'Apartment' }); units.push(u.id)
   const p = await post<{ id: string }>('/people', { code: 'MEETING-' + code, kind: 'NaturalPerson', firstName: 'Synthetic', lastNameOrCompany: 'Meeting ' + code, taxCode: 'SYNTHETIC-MEETING-' + code, email: 'meeting-' + code.toLowerCase() + '@test.invalid' }); people.push(p.id)
   await post('/condominiums/' + c.id + '/units/' + u.id + '/associations', { personId: p.id, role: 'Owner', validFrom: '2026-01-01', fraction: '1' })
  }
  const table = await post<{ id: string }>('/condominiums/' + c.id + '/allocation-tables', { code: 'MEETING', name: 'Proprietà sintetica', denominator: '1000', validFrom: '2026-01-01' })
  for (let i = 0; i < 2; i++) await post('/condominiums/' + c.id + '/allocation-tables/' + table.id + '/entries/' + units[i], { value: i === 0 ? '120' : '880' }, 'PUT')
  await post('/condominiums/' + c.id + '/allocation-tables/' + table.id + '/activate', {})
  return { condo: c.id, units, people, table: table.id }
 })
 await page.reload()
 await page.getByRole('button', { name: 'Assemblee', exact: true }).click()
 await page.getByRole('combobox', { name: 'Condominio', exact: true }).selectOption(seed.condo)
 await page.getByRole('button', { name: 'Nuova assemblea', exact: true }).click()
 await page.getByLabel('Titolo *', { exact: true }).fill('Assemblea ordinaria sintetica')
 await page.getByLabel('Luogo *', { exact: true }).fill('Sala sintetica')
 await page.getByRole('textbox', { name: /^Prima convocazione/ }).fill('2026-12-10T07:00:00+01:00')
 await page.getByLabel('Seconda convocazione facoltativa').fill('2026-12-11T20:30:00+01:00')
 await page.getByRole('button', { name: 'Salva', exact: true }).click()
 await expect(page.getByRole('heading', { name: /Assemblea ordinaria sintetica · Draft/ })).toBeVisible()
 await page.getByRole('button', { name: 'Nuovo punto', exact: true }).click()
 await page.getByLabel('Titolo punto *', { exact: true }).fill('Esame consuntivo sintetico')
 await page.getByRole('button', { name: 'Salva', exact: true }).click()
 await expect(page.getByRole('cell', { name: 'Esame consuntivo sintetico', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Aventi diritto', exact: true }).click()
 await page.getByLabel('Data riferimento *', { exact: true }).fill('2026-11-01')
 await page.getByRole('combobox', { name: 'Tabella millesimale informativa' }).selectOption(seed.table)
 await page.getByLabel('Motivo consolidamento o riconciliazione *', { exact: true }).fill('Verifica anagrafica sintetica')
 await page.getByRole('button', { name: 'Salva', exact: true }).click()
 await page.getByRole('button', { name: 'Consolida snapshot partecipanti', exact: true }).click()
 await expect(page.getByRole('button', { name: 'Consolida snapshot partecipanti', exact: true })).toHaveCount(0)
 await page.getByRole('button', { name: 'Convocazioni', exact: true }).click()
 for (const person of seed.people) {
  await page.getByRole('button', { name: 'Prepara convocazione', exact: true }).click()
  await page.getByRole('combobox', { name: 'Destinatario *', exact: true }).selectOption(person)
  await page.getByLabel('Recapito verificato manualmente *', { exact: true }).fill('synthetic@test.invalid')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Convocazione manuale' })).toHaveCount(0)
 }
 await page.getByRole('button', { name: 'Dichiara Ready', exact: true }).first().click()
 await page.getByRole('button', { name: 'Dichiara Sent', exact: true }).click()
 await expect(page.getByText(/Sent · .*dichiarazione non verificata/)).toBeVisible()
 await page.getByRole('button', { name: 'Assemblea', exact: true }).click()
 await page.getByRole('button', { name: 'Programma', exact: true }).click()
 await page.getByRole('button', { name: 'Consolida convocazione', exact: true }).click()
 await expect(page.getByRole('heading', { name: /Assemblea ordinaria sintetica · Convened/ })).toBeVisible()
 await page.getByRole('button', { name: 'Deleghe', exact: true }).click()
 await page.getByRole('button', { name: 'Nuova delega', exact: true }).click()
 await page.getByLabel('Unità A', { exact: true }).check()
 await page.getByRole('combobox', { name: 'Delegante *', exact: true }).selectOption(seed.people[0])
 await page.getByRole('combobox', { name: 'Delegato *', exact: true }).selectOption(seed.people[1])
 await page.getByLabel('Riferimento documento delega').fill('DELEGA-SINTETICA')
 await page.getByRole('button', { name: 'Salva', exact: true }).click()
 await page.getByRole('button', { name: 'Presenta delega', exact: true }).click()
 await page.getByRole('button', { name: 'Verifica delega', exact: true }).click()
 await expect(page.getByRole('cell', { name: /Verified/ })).toBeVisible()
 await page.getByRole('button', { name: 'Assemblea', exact: true }).click()
 await page.getByRole('button', { name: 'Non tenuta First', exact: true }).click()
 await page.getByRole('button', { name: 'Avvia Second', exact: true }).click()
 await page.getByRole('button', { name: 'Presenze', exact: true }).click()
 await page.getByRole('button', { name: 'Registra presenza', exact: true }).click()
 await page.getByLabel('Unità A', { exact: true }).check()
 await page.getByRole('combobox', { name: 'Sessione presenza *', exact: true }).selectOption({ label: 'Second · InProgress' })
 await page.getByRole('combobox', { name: 'Titolare rappresentato *', exact: true }).selectOption(seed.people[0])
 await page.getByRole('combobox', { name: 'Modalità presenza *', exact: true }).selectOption('ByProxy')
 await page.getByRole('combobox', { name: 'Delega verificata' }).selectOption({ label: 'Synthetic Meeting A → Synthetic Meeting B' })
 await page.getByRole('button', { name: 'Salva', exact: true }).click()
 await expect(page.getByText(/Presenti effettivi: 1 · unità rappresentate: 1 · millesimi informativi: 120/)).toBeVisible()
 await expect(page.getByRole('cell', { name: /ByProxy/ })).toBeVisible()
 await page.screenshot({ path: '../../../.artifacts/meeting-desktop.png', fullPage: true })
 await page.setViewportSize({ width: 390, height: 844 })
 await page.screenshot({ path: '../../../.artifacts/meeting-mobile.png', fullPage: true })
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
 await page.getByRole('button', { name: 'Registra uscita', exact: true }).click()
 await expect(page.getByText(/Presenti effettivi: 0 · unità rappresentate: 0/)).toBeVisible()
})
