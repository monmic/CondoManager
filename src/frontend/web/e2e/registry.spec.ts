import { test, expect } from '@playwright/test'

test('anagrafiche, associazioni, millesimi ed esercizi su PostgreSQL', async ({ page }) => {
  test.skip(!process.env.CONDOMANAGER_E2E, 'Avviare scripts/Verify-Postgres.ps1 -Browser su database isolato.')
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill(process.env.CONDOMANAGER_E2E_EMAIL!)
  await page.getByLabel('Password', { exact: true }).fill(process.env.CONDOMANAGER_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Accedi', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Condomini', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo condominio' }).click()
  await page.getByLabel('Codice interno').fill('C-E2E')
  await page.getByLabel('Denominazione').fill('Condominio sintetico E2E')
  await page.getByLabel('Indirizzo').fill('Indirizzo sintetico')
  await page.getByLabel('CAP').fill('00000')
  await page.getByLabel('Comune').fill('Comune sintetico')
  await page.getByLabel('Provincia').fill('XX')
  await page.getByLabel('Stato').fill('Test')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Condominio sintetico E2E', exact: true })).toBeVisible()
  for (const code of ['U-01', 'U-02']) {
    await page.getByRole('button', { name: 'Nuova unita', exact: true }).click()
    await page.getByLabel('Codice unita').fill(code)
    await page.getByRole('button', { name: 'Salva', exact: true }).click()
    await expect(page.getByRole('cell', { name: code, exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Anagrafiche', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo soggetto' }).click()
  await page.getByLabel('Codice interno').fill('P-E2E')
  await page.getByLabel(/^Nome/).fill('Soggetto')
  await page.getByLabel('Cognome / ragione sociale').fill('Sintetico E2E')
  await page.getByLabel('Codice fiscale').fill('SYNTHETIC-E2E')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Soggetto Sintetico E2E', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Condomini', exact: true }).click()
  await page.getByRole('button', { name: 'Associa soggetto' }).click()
  await page.getByLabel('Unita').selectOption({ label: 'U-01' })
  await page.getByLabel('Soggetto').selectOption({ label: 'Soggetto Sintetico E2E (P-E2E)' })
  await page.getByLabel('Quota proprieta').fill('1')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Soggetto Sintetico E2E', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Tabelle millesimali', exact: true }).click()
  await page.getByRole('button', { name: 'Nuova tabella' }).click()
  await page.getByLabel('Codice tabella').fill('T-E2E')
  await page.getByLabel('Denominazione').fill('Proprieta sintetica E2E')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await expect(page.getByText('Quote mancanti:', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Attiva', exact: true })).toBeDisabled()
  for (const [code, value] of [['U-01', '333.333333'], ['U-02', '666.666667']]) {
    const input = page.getByLabel('Quota ' + code)
    await input.fill(value)
    await input.locator('..').getByRole('button', { name: 'Salva quota' }).click()
    await expect(page.getByRole('cell', { name: value, exact: true })).toBeVisible()
  }
  await expect(page.getByRole('button', { name: 'Attiva', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Attiva', exact: true }).click()
  await expect(page.locator('span.badge').filter({ hasText: /^Attiva$/ })).toBeVisible()
  await expect(page.getByLabel('Quota U-01')).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Esercizi contabili', exact: true }).click()
  await page.getByRole('button', { name: 'Nuovo esercizio' }).click()
  await page.getByLabel('Codice esercizio').fill('E-E2E')
  await page.getByLabel('Denominazione').fill('Esercizio sintetico E2E')
  await page.getByLabel('Data inizio').fill('2026-07-01')
  await page.getByLabel('Data fine (inclusa)').fill('2027-06-30')
  await page.getByRole('button', { name: 'Salva', exact: true }).click()
  await page.getByRole('button', { name: 'Apri esercizio', exact: true }).click()
  await expect(page.getByText('Open', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Chiudi definitivamente', exact: true }).click()
  await expect(page.getByText('Closed', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Condomini', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Condominio sintetico E2E', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Condomini', exact: true })).toBeVisible()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 390)
  await page.screenshot({ path: test.info().outputPath('mobile.png'), fullPage: true })
})
